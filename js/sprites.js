const SPRITE_TONES = { a: '--c3', b: '--c2', c: '--c1', d: '--c0' };
// Colores propios de un sprite (opcional): { a, b, c, d } en hex. Ganan sobre la paleta del mundo.
// El Mundo 2 los usa para que cada sprite tenga sus 3 colores, como en la NES.
const SPRITE_PALETTES = {};

function paletteColors() {
  const css = getComputedStyle(document.body);
  const colors = {};
  for (const k in SPRITE_TONES) colors[k] = css.getPropertyValue(SPRITE_TONES[k]).trim();
  return colors;
}

// Pinta un sprite dentro de un canvas ya existente, en la posición (ox, oy).
// Un sprite puede traer su propia paleta fija (rows.pal = { R: '#e8393d', ... }) para tener
// más de 4 colores (por ejemplo, los del Reino 16-Bit). Las letras que no estén en rows.pal
// usan los 4 tonos del mundo, como siempre.
function paintSprite(g, name, ox, oy, scale, colors, silhouette = false) {
  const rows = SPRITES[name];
  if (!rows) return;
  const pal = rows.pal || {};
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      g.fillStyle = silhouette ? colors.c : pal[ch] || colors[ch];
      g.fillRect(ox + x * scale, oy + y * scale, scale, scale);
    }
  });
}

// Dibuja un sprite en un <canvas>. Con silhouette:true sale todo de un solo tono
// (para cosas que todavía no se descubren).
function drawSprite(canvas, name, { scale = 4, silhouette = false } = {}) {
  if (!canvas || !SPRITES[name]) return;
  canvas.width = 16 * scale;
  canvas.height = 16 * scale;
  const g = canvas.getContext('2d');
  g.clearRect(0, 0, canvas.width, canvas.height);
  paintSprite(g, name, 0, 0, scale, { ...paletteColors(), ...SPRITE_PALETTES[name] }, silhouette);
}

