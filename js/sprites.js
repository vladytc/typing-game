// Casillas repetitivas generadas con código (pasto, camino, agua, techo, ladrillo).
function tileFrom(base, marks) {
  const g = Array.from({ length: 16 }, () => Array(16).fill(base));
  marks.forEach(([x, y, c]) => { if (g[y] && g[y][x]) g[y][x] = c; });
  return g.map((r) => r.join(''));
}
function speckles(n, seed, ch) {
  let s = seed;
  const rnd = () => (s = (s * 9301 + 49297) % 233280) / 233280;
  return Array.from({ length: n }, () => [Math.floor(rnd() * 16), Math.floor(rnd() * 16), ch]);
}
const tufts = (spots, ch) => spots.flatMap(([x, y]) => [[x, y, ch], [x + 1, y + 1, ch], [x + 2, y, ch]]);
const rowsOf = (fn) => Array.from({ length: 16 }, (_, y) => Array.from({ length: 16 }, (_, x) => fn(x, y)).join(''));

